import test, { beforeEach, afterEach } from "node:test";
import assert from "node:assert/strict";
import { buildEmailReport } from "../../src/hyrox/reports/emailReportBuilder.js";
import { buildPersonalReport } from "../../src/hyrox/reports/personalReportBuilder.js";
import { buildPredictorEmailContent } from "../../src/hyrox/reports/predictorEmailTemplate.js";
import { buildRunningProfilerEmail } from "../../src/hyrox/running/runningProfilerEmailService.js";
import { createSharePackHandlers } from "../../src/hyrox/hyroxSharePackController.js";
import { reportFixture } from "../../src/hyrox/reports/__tests__/fixtures/reportFixture.js";
let previous;
beforeEach(() => {
  previous = { ...process.env };
  process.env.BRAND_VARIANT = "200days";
  for (const key of ["BASE_URL", "FORMA_APP_BASE_URL", "FORMA_CTA_URL", "APP_BASE_URL"]) delete process.env[key];
});
afterEach(() => { process.env = previous; });
function check(email) {
  const all = Object.values(email).join("\n");
  assert.doesNotMatch(all, /\bforma\b|getforma/i);
  assert.match(email.html ?? email.htmlBody, /200 Days/);
  for (const [, href] of all.matchAll(/href="(https:\/\/[^"\s]+)"/g)) assert.ok(["200days.app", "download.example.test"].includes(new URL(href).hostname), href);
}
for (const mode of ["analyse", "target"]) test(`200 Days ${mode} report has hosted logos and current links`, () => {
  const [, analysis, athlete] = reportFixture();
  const report = buildPersonalReport(analysis, [], athlete, null, mode);
  const email = buildEmailReport(report, analysis, athlete, null, mode, null, analysis.submissionId);
  check(email);
  assert.doesNotMatch(email.htmlBody, /data:image/);
  assert.match(email.htmlBody, /Build your next HYROX block in the 200 Days app/);
  assert.match(email.htmlBody, /background-color:#3B82F6;color:#ffffff/);
  assert.match(email.htmlBody, /200 days changes everything/);
});
test("predictor result has team signoff and branded footer", () => {
  const email = buildPredictorEmailContent({ predictedFinishFormatted: "1:20:00" }, { name: "Alex" });
  check(email);
  assert.match(email.html, /The 200 Days team/);
  assert.match(email.html, /href="https:\/\/200days.app">200days.app/);
});
const runningAnalysis = { confidence: "high", analysis: {
  keyInsight: "Keep building endurance", overallPerformanceScore: 70, runningCapacityScore: 70,
  balanceScore: 65, performanceTranslation: { note: "Estimated from recent results" },
  tradeOffOutlook: "Build gradually", recommendations: [],
} };
test("running profile exposes a synchronous branded builder", () => {
  const email = buildRunningProfilerEmail({ display_name: "Alex", email: "alex@example.test" }, runningAnalysis);
  check(email);
  assert.match(email.text, /^200 Days — Running/);
  assert.match(email.html, /height="36"/);
  assert.match(email.html, /Generated by <strong[^>]*>200 Days<\/strong> · 200days.app/);
});
test("share-pack email preserves the signed download URL and expiry", async () => {
  let email;
  const handlers = createSharePackHandlers({}, {
    getOrCreateSharePack: async () => ({}), getPackDownloadUrl: async () => "https://download.example.test/pack.zip?signature=abc",
    sendEmail: async value => { email = value; }, logCalculatorEvent: async () => {},
  });
  await handlers.sendPackEmail({ params: { submissionId: "test" }, body: { email: "alex@example.test" } }, { json: value => value });
  check(email);
  assert.equal(email.subject, "Your HYROX Instagram pack from 200 Days");
  assert.match(email.text, /This link expires in 7 days\.\n\nThe 200 Days team/);
});
test("unset flag retains the Forma report header and running title", () => {
  delete process.env.BRAND_VARIANT;
  assert.match(buildEmailReport(...reportFixture()).htmlBody, /alt="Forma — Measure/);
  assert.match(buildRunningProfilerEmail({ email: "alex@example.test" }, runningAnalysis).text, /^FORMA — Running/);
});

test("report URL overrides are read on each call", () => {
  for (const [key, path] of [["FORMA_APP_BASE_URL", "/hyrox-calculator/race-details"], ["FORMA_CTA_URL", "/hyrox-calculator/race-details"], ["APP_BASE_URL", "/api/hyrox/download-redirect/"]]) {
    for (const host of ["first.example.test", "second.example.test"]) {
      process.env[key] = `https://${host}`;
      const args = reportFixture();
      const email = buildEmailReport(...args, null, args[1].submissionId);
      assert.ok(email.htmlBody.includes(`https://${host}${path}`), key);
    }
    delete process.env[key];
  }
});
